func TestToServers(t *testing.T) {
	entries := []Entry{
		{Address: "192.168.1.1", Iface: "en0", Role: RolePrimary},
		{Address: "192.168.1.1", Iface: "utun3", Role: RolePrimary},
		{Address: "fe80::1%en0", Iface: "en0", Role: RoleSecondary},
		{Address: "8.8.8.8", Iface: "", Role: RolePrimary},
	}
	servers, ifaces := toServers(entries)
	if len(servers) != 3 {
		t.Fatalf("got %d servers %v, want 3", len(servers), servers)
	}
	first := servers[0]
	if first.ID != "system-en0-192-168-1-1" {
		t.Errorf("ID = %q, want %q", first.ID, "system-en0-192-168-1-1")
	}
	if first.Name != "System (en0) 192.168.1.1" {
		t.Errorf("Name = %q, want %q", first.Name, "System (en0) 192.168.1.1")
	}
	if first.Interface != "en0" || first.SystemRole != RolePrimary {
		t.Errorf("Interface/SystemRole = %q/%q, want en0/primary", first.Interface, first.SystemRole)
	}
	if first.Source != model.SourceSystem || first.Protocol != model.ProtoUDP || first.Port != 53 || !first.Enabled {
		t.Errorf("unexpected server metadata: %+v", first)
	}
	second := servers[1]
	if second.Address != "fe80::1%en0" {
		t.Errorf("Address = %q, want zone kept intact", second.Address)
	}
	if second.ID != "system-en0-fe80-1-en0" {
		t.Errorf("ID = %q, want %q", second.ID, "system-en0-fe80-1-en0")
	}
	third := servers[2]
	if third.ID != "system-8-8-8-8" {
		t.Errorf("ID = %q, want %q", third.ID, "system-8-8-8-8")
	}
	if third.Name != "System 8.8.8.8" {
		t.Errorf("Name = %q, want %q", third.Name, "System 8.8.8.8")
	}
	wantIfaces := []string{"en0", "utun3"}
	if len(ifaces) != len(wantIfaces) {
		t.Fatalf("ifaces = %v, want %v", ifaces, wantIfaces)
	}
	for i := range wantIfaces {
		if ifaces[i] != wantIfaces[i] {
			t.Errorf("ifaces[%d] = %q, want %q", i, ifaces[i], wantIfaces[i])
		}
	}
}
